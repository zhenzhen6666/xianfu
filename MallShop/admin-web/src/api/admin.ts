import { http } from './http'
import type {
  Activity,
  AdminUser,
  AfterSale,
  Category,
  Coupon,
  CouponIssue,
  CouponPayload,
  Dashboard,
  DeliveryConfig,
  HomeModule,
  LoginResult,
  Order,
  OrderDetail,
  OrderNotification,
  Product,
  ProductPayload,
  ProductSku,
  AfterSaleDetail,
  CouponBatchResult,
  CouponIssueRecord,
  ErrorLog,
  BusinessAlert,
  PaymentCallbackLog,
  AuthSession,
} from '../types/api'

const data = <T>(request: Promise<{ data: T }>) => request.then((response) => response.data)

export const adminApi = {
  login: (nickname: string, secret: string) => data<LoginResult>(http.post('/auth/dev-admin-login', { nickname, secret })),
  logout: (refreshToken: string) => data(http.post('/auth/logout', { refreshToken })),
  dashboard: () => data<Dashboard>(http.get('/admin/dashboard')),
  products: (status = 'ALL') => data<Product[]>(http.get('/admin/products', { params: { status } })),
  createProduct: (payload: ProductPayload) => data<Product>(http.post('/admin/products', payload)),
  updateProduct: (code: string, payload: ProductPayload) => data<Product>(http.put(`/admin/products/${code}`, payload)),
  productSkus: (code: string) => data<ProductSku[]>(http.get(`/admin/products/${code}/skus`)),
  updateProductSkus: (code: string, skus: ProductSku[]) => data<ProductSku[]>(http.put(`/admin/products/${code}/skus`, { skus })),
  orders: (status = 'ALL', page = 0, size = 100) => data<Order[]>(http.get('/admin/orders', { params: { status, page, size } })),
  order: (orderNo: string) => data<OrderDetail>(http.get(`/admin/orders/${orderNo}`)),
  orderNotifications: () => data<OrderNotification[]>(http.get('/admin/order-notifications')),
  unreadOrderNotificationCount: () => data<{ count: number }>(http.get('/admin/order-notifications/unread-count')),
  readOrderNotification: (orderNo: string) => data<OrderNotification>(http.patch(`/admin/order-notifications/${orderNo}/read`)),
  acceptOrderNotification: (orderNo: string) => data<OrderNotification>(http.patch(`/admin/order-notifications/${orderNo}/accept`)),
  updateOrderStatus: (orderNo: string, status: string) => data(http.patch(`/admin/orders/${orderNo}/status`, { status })),
  refund: (orderNo: string, amount: number, reason: string) => data(http.post(`/admin/orders/${orderNo}/refund`, { amount, reason })),
  delivery: () => data<DeliveryConfig>(http.get('/admin/delivery-config')),
  updateDelivery: (payload: Omit<DeliveryConfig, 'id' | 'updatedAt'>) => data<DeliveryConfig>(http.put('/admin/delivery-config', payload)),
  users: (keyword = '') => data<AdminUser[]>(http.get('/admin/users', { params: { keyword: keyword || undefined } })),
  updateUserStatus: (id: number, status: string) => data(http.patch(`/admin/users/${id}/status`, { status })),
  coupons: () => data<Coupon[]>(http.get('/admin/coupons')),
  createCoupon: (payload: CouponPayload) => data<Coupon>(http.post('/admin/coupons', payload)),
  updateCoupon: (code: string, payload: CouponPayload) => data<Coupon>(http.put(`/admin/coupons/${code}`, payload)),
  voidCoupon: (code: string) => data(http.delete(`/admin/coupons/${code}`)),
  issueCoupon: (code: string, mobile: string) => data<CouponIssue>(http.post(`/admin/coupons/${code}/issues`, { mobile })),
  batchIssueCoupon: (code: string, mobiles: string[]) => data<CouponBatchResult>(http.post(`/admin/coupons/${code}/batch-issues`, { mobiles })),
  couponIssueRecords: (couponCode?: string) => data<CouponIssueRecord[]>(http.get('/admin/coupon-issue-records', { params: { couponCode } })),
  afterSales: (status = 'ALL') => data<AfterSale[]>(http.get('/admin/after-sales', { params: { status } })),
  afterSale: (no: string) => data<AfterSaleDetail>(http.get(`/admin/after-sales/${no}`)),
  updateAfterSale: (no: string, status: string, reply: string, refundAmount?: number) => data(http.patch(`/admin/after-sales/${no}`, { status, reply, refundAmount })),
  categories: () => data<Category[]>(http.get('/admin/categories')),
  saveCategory: (code: string, payload: Omit<Category, 'code'>) => data<Category[]>(http.put(`/admin/categories/${code}`, payload)),
  homeModules: () => data<HomeModule[]>(http.get('/admin/home-modules')),
  createHomeModule: (payload: Omit<HomeModule, 'id' | 'publishedAt' | 'updatedAt'>) => data<HomeModule[]>(http.post('/admin/home-modules', payload)),
  updateHomeModule: (id: number, payload: Omit<HomeModule, 'id' | 'publishedAt' | 'updatedAt'>) => data<HomeModule[]>(http.put(`/admin/home-modules/${id}`, payload)),
  deleteHomeModule: (id: number) => data(http.delete(`/admin/home-modules/${id}`)),
  activities: () => data<Activity[]>(http.get('/admin/activities')),
  updateActivity: (code: string, payload: Omit<Activity, 'code'>) => data<Activity>(http.put(`/admin/activities/${code}`, payload)),
  errorLogs: () => data<ErrorLog[]>(http.get('/admin/operations/errors')),
  alerts: (status = 'ALL') => data<BusinessAlert[]>(http.get('/admin/operations/alerts', { params: { status } })),
  acknowledgeAlert: (id: number) => data(http.patch(`/admin/operations/alerts/${id}/acknowledge`)),
  paymentCallbacks: () => data<PaymentCallbackLog[]>(http.get('/admin/operations/payment-callbacks')),
  sessions: () => data<AuthSession[]>(http.get('/admin/operations/sessions')),
  revokeSession: (id: string) => data(http.delete(`/admin/operations/sessions/${id}`)),
}
